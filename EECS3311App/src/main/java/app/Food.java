package app;

public class Food {
	 protected int foodId;          
	 public String name;

	    
	    
	    public Food(int foodId, String name) {
	        this.foodId = foodId;
	        this.name = name;
	    }
	    
	    
	    
	    public int getFoodId() {
	        return foodId;
	    }
	    

	    
	    public String getName() {
	    	return name;
	    }

}
